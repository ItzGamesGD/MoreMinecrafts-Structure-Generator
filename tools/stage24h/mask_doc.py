"""Write stage-24h/MASK.md: the mask rules and, per module, a layer-by-layer map of every cell's class."""
from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.stage24c.common import MODULES  # noqa: E402
from tools.stage24g.roles import Template  # noqa: E402
from tools.stage24h import mask as M  # noqa: E402
from tools.stage24h.build import D24F, D24H  # noqa: E402

SYM = {"stored_architecture": "#", "room_interior": "R", "walkway": "W", "paved_walkway": "P", "step_headroom": "H",
       "interaction_space": "C", "pool_headroom": "O", "decorative_void": ":", "exterior": "."}
DOC = (M.__doc__ or "").strip()


def main():
    out = ["# Stage 24-H — interior clearance masks", "", "Generated by `tools/stage24h/mask_doc.py` from `tools/stage24h/mask.py` "
           "(the source of truth is `mask/interior-masks.json`, which lists every cleared cell in local template coordinates "
           "x, y, z, before rotation).", "", "## Rules", "", "```", DOC, "```", "",
           "Courtyard rule: an enclosed walkable cell with no ceiling clears its two body cells and one jump-headroom cell "
           "only — never the column above. Paving outside an enclosure clears body height only.", "",
           "| module | size | " + " | ".join(SYM) + " | cleared |", "|---|---|" + "---|" * len(SYM) + "---|"]
    maps = []
    for m in MODULES:
        t = Template(D24F / m / "restored.nbt")
        full = M.build_mask(t)
        c = Counter(full.values())
        out.append(f"| {m} | {'×'.join(map(str, t.size))} | " + " | ".join(str(c.get(k, 0)) for k in SYM) +
                   f" | **{sum(c.get(k, 0) for k in M.CLEARED)}** |")
        maps += [f"### {m}", "", "Legend: " + ", ".join(f"`{v}` {k}" for k, v in SYM.items()) + ". Rows = z (0 at top), columns = x (0 at left).", ""]
        for y in range(t.size[1]):
            if not any(full[(x, y, z)] in M.CLEARED for x in range(t.size[0]) for z in range(t.size[2])):
                continue
            maps.append(f"y = {y}")
            maps.append("```")
            for z in range(t.size[2]):
                maps.append("".join(SYM[full[(x, y, z)]] for x in range(t.size[0])))
            maps.append("```")
        maps.append("")
    out.append("")
    out.append("Layers without a cleared cell are omitted below.")
    out.append("")
    (D24H / "MASK.md").write_text("\n".join(out + maps) + "\n")


if __name__ == "__main__":
    main()
